package main

import (
	"os"
	"path/filepath"
	"testing"
)

// The generator copies only the command names of each version's
// InspectorBackendCommands.js (InspectorBackend.registerCommand calls),
// deduplicated and sorted, and orders versions numerically (16.4 before
// 16.10 before 26.0). Other files are ignored.
func TestGenerateExtractsCommandListsByVersion(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"iOS-26.0-InspectorBackendCommands.js":   `InspectorBackend.registerCommand("Page.reload", [], []);` + "\n" + `InspectorBackend.registerEvent("Page.loadEventFired", []);`,
		"iOS-16.10-InspectorBackendCommands.js":  `InspectorBackend.registerCommand("Runtime.evaluate", [{"name": "expression"}], ["result"]);`,
		"iOS-16.4-InspectorBackendCommands.js":   `InspectorBackend.registerCommand("DOM.getDocument", [], []);` + "\n" + `InspectorBackend.registerCommand("CSS.enable", [], []);` + "\n" + `InspectorBackend.registerCommand("CSS.enable", [], []);`,
		"macOS-15.0-InspectorBackendCommands.js": `InspectorBackend.registerCommand("Browser.enable", [], []);`,
		"README":                                 "not a command list",
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := generate(dir)
	if err != nil {
		t.Fatal(err)
	}
	want := "// Code generated by go run internal/wip/gen/main.go; DO NOT EDIT.\n\n" +
		"package wip\n\n" +
		"// commandLists are the protocol commands of each iOS version's Web\n// Inspector backend, oldest first; methods are space-separated.\n" +
		"var commandLists = []commandList{\n" +
		"\t{major: 16, minor: 4, methods: \"CSS.enable DOM.getDocument\"},\n" +
		"\t{major: 16, minor: 10, methods: \"Runtime.evaluate\"},\n" +
		"\t{major: 26, minor: 0, methods: \"Page.reload\"},\n" +
		"}\n"
	if string(got) != want {
		t.Fatalf("generated:\n%s\nwant:\n%s", got, want)
	}
	if _, err := generate(filepath.Join(dir, "missing")); err == nil {
		t.Fatal("generate on a missing directory succeeded")
	}
}
