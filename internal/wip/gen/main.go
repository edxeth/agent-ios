// gen writes methods_gen.go from WebKit's per-iOS-version
// InspectorBackendCommands.js files (the Web Inspector frontend's command
// lists, BSD-licensed WebKit sources). Only method names are copied.
//
//	go run internal/wip/gen/main.go <dir with iOS-<version>-InspectorBackendCommands.js>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	fileRe    = regexp.MustCompile(`^iOS-(\d+)\.(\d+)-InspectorBackendCommands\.js$`)
	commandRe = regexp.MustCompile(`registerCommand\("([A-Za-z]+\.[A-Za-z]+)"`)
)

type list struct {
	major, minor int
	methods      []string
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run internal/wip/gen/main.go <dir>")
		os.Exit(2)
	}
	src, err := generate(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("internal/wip/methods_gen.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// generate reads every iOS-<major>.<minor>-InspectorBackendCommands.js in
// dir and returns the formatted source of methods_gen.go: one list per
// version, oldest first, each with its distinct command names sorted.
func generate(dir string) ([]byte, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var lists []list
	for _, e := range entries {
		m := fileRe.FindStringSubmatch(e.Name())
		if m == nil {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		seen := map[string]bool{}
		var methods []string
		for _, c := range commandRe.FindAllStringSubmatch(string(data), -1) {
			if !seen[c[1]] {
				seen[c[1]] = true
				methods = append(methods, c[1])
			}
		}
		sort.Strings(methods)
		major, _ := strconv.Atoi(m[1])
		minor, _ := strconv.Atoi(m[2])
		lists = append(lists, list{major, minor, methods})
	}
	sort.Slice(lists, func(i, j int) bool {
		if lists[i].major != lists[j].major {
			return lists[i].major < lists[j].major
		}
		return lists[i].minor < lists[j].minor
	})
	var b bytes.Buffer
	b.WriteString("// Code generated by go run internal/wip/gen/main.go; DO NOT EDIT.\n\n")
	b.WriteString("package wip\n\n")
	b.WriteString("// commandLists are the protocol commands of each iOS version's Web\n// Inspector backend, oldest first; methods are space-separated.\n")
	b.WriteString("var commandLists = []commandList{\n")
	for _, l := range lists {
		fmt.Fprintf(&b, "\t{major: %d, minor: %d, methods: %q},\n", l.major, l.minor, strings.Join(l.methods, " "))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
